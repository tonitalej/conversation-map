// Builds the viewer (browser IIFE + CSS) and the dependency-free CLI bundle shipped in the plugin.
import { build, transform } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'build');
const pluginScript = join(root, 'plugins/conversation-map/skills/conversation-map/scripts/conversation-map.mjs');

const viewer = await build({
  entryPoints: [join(root, 'src/viewer/main.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020', 'chrome100', 'firefox100', 'safari15'],
  minify: true,
  legalComments: 'none',
  write: false,
});
const script = viewer.outputFiles[0].text.trim();

const css = await transform(readFileSync(join(root, 'src/viewer/styles.css'), 'utf8'), {
  loader: 'css',
  minify: true,
  target: ['chrome100', 'firefox100', 'safari15'],
});
const style = css.code.trim();

if (script.includes('</script') || style.includes('</style')) throw new Error('Viewer assets contain a closing tag.');

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'viewer.js'), script);
writeFileSync(join(outDir, 'viewer.css'), style);

await build({
  entryPoints: [join(root, 'src/cli/main.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node18',
  outfile: pluginScript,
  legalComments: 'none',
  banner: {
    js: '#!/usr/bin/env node\n// Generated by scripts/build.mjs from src/. Do not edit; rebuild with `npm run build`.',
  },
  plugins: [
    {
      name: 'viewer-assets',
      setup(b) {
        b.onResolve({ filter: /^virtual:viewer-assets$/ }, () => ({ path: 'viewer-assets', namespace: 'virtual' }));
        b.onLoad({ filter: /.*/, namespace: 'virtual' }, () => ({
          contents: `export const VIEWER_SCRIPT = ${JSON.stringify(script)};\nexport const VIEWER_STYLE = ${JSON.stringify(style)};\n`,
          loader: 'js',
        }));
      },
    },
  ],
});

console.log(`viewer: ${(script.length / 1024).toFixed(1)} KiB js, ${(style.length / 1024).toFixed(1)} KiB css`);
console.log(
  `cli:    ${pluginScript.slice(root.length + 1)} (${(readFileSync(pluginScript).length / 1024).toFixed(1)} KiB)`,
);
